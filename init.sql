-- Триггер для автоматического создания штрафа при просрочке
CREATE OR REPLACE FUNCTION create_fine_on_overdue()
RETURNS TRIGGER AS $$
DECLARE
    days_overdue INTEGER;
    fine_amount DECIMAL(10,2);
BEGIN
    -- Проверяем, что книга возвращена и есть просрочка
    IF NEW.return_date IS NOT NULL AND NEW.return_date > NEW.due_date THEN
        days_overdue := EXTRACT(DAY FROM (NEW.return_date - NEW.due_date));
        fine_amount := days_overdue * 0.5;
        
        -- Проверяем, не создан ли уже штраф для этого займа
        IF NOT EXISTS (SELECT 1 FROM Fines WHERE loan_id = NEW.loan_id) THEN
            INSERT INTO Fines (loan_id, amount, paid, fine_date)
            VALUES (NEW.loan_id, fine_amount, FALSE, CURRENT_TIMESTAMP);
        END IF;
    END IF;
    
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trigger_create_fine_on_overdue
AFTER UPDATE ON Loans
FOR EACH ROW
WHEN (NEW.return_date IS NOT NULL AND OLD.return_date IS NULL)
EXECUTE FUNCTION create_fine_on_overdue();

